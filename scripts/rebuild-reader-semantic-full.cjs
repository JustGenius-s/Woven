const fs=require('node:fs/promises');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {createHash}=require('node:crypto');
const JSZip=require('jszip');
const {buildFullModel}=require('./lib/reader-book/semantic-full-layout.cjs');
const {preview,renderBlock,collectDiagrams}=require('./lib/reader-book/semantic-preview.cjs');
const {readGraphics}=require('./lib/reader-book/pdf-graphics.cjs');
const root=path.resolve(__dirname,'..');
const option=(name,fallback)=>process.argv.includes(name)?process.argv[process.argv.indexOf(name)+1]:fallback;
const escape=s=>String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/"/g,'&quot;');

async function main(){
  const config=require('../content/reader-semantic-full/book.cjs');
  const work=path.join(root,'.cache/reader-semantic-full-source');
  if(process.argv.includes('--refresh-source')) {
    const pdf=option('--pdf');if(!pdf)throw new Error('--refresh-source requires --pdf /path/to/original.pdf');
    await fs.mkdir(work,{recursive:true});
    execFileSync(option('--python','python'),[path.join(__dirname,'lib/reader-book/import-pdf2htmlex.py'),'--epub',path.join(root,config.fixedEpub),
      '--pages',config.pages.map(p=>p.number).join(','),'--out',work],{windowsHide:true,stdio:'pipe'});
    await fs.writeFile(path.join(work,'pdf-graphics.json'),JSON.stringify(await readGraphics(pdf,config.pages.map(p=>p.number),config.pdfSha256)));
  }
  const htmlSource=JSON.parse(await fs.readFile(path.join(work,'html-source.json'),'utf8'));
  const pdfSource=JSON.parse(await fs.readFile(path.join(work,'pdf-graphics.json'),'utf8'));
  if(pdfSource.sha256!==config.pdfSha256)throw new Error('The source PDF does not match the page profile.');
  const {model,assets,audit}=buildFullModel(config,htmlSource,pdfSource,work);
  const out=path.join(root,'docs/previews');await fs.mkdir(out,{recursive:true});
  await fs.writeFile(path.join(out,'reader-semantic-full.json'),JSON.stringify(model));
  await fs.writeFile(path.join(out,'reader-semantic-full-audit.json'),JSON.stringify(audit,null,2)+'\n');
  await fs.writeFile(path.join(out,'reader-semantic-full.html'),preview(model,assets,work));
  await fs.writeFile(path.join(out,'reader-semantic-full-config.json'),JSON.stringify(config,null,2)+'\n');
  const zip=new JSZip(),date=new Date('2026-09-09T00:00:00Z');
  const add=(name,bytes)=>zip.file(name,bytes,{date});
  const assetUrl=name=>'semantic-assets/'+name;
  assetUrl.chapterLink=id=>id+'.html';
  for(const chapter of model.chapters) {
    add(chapter.id+'.html','<!doctype html><html lang="ja"><head><meta charset="utf-8"/>'+
      '<meta name="viewport" content="width=device-width,initial-scale=1"/>'+
      `<title>${escape(chapter.title)}</title><link rel="stylesheet" href="semantic.css"/><link rel="stylesheet" href="reader-web.css"/></head>`+
      `<body id="reading"><article class="chapter" id="${chapter.id}">${chapter.blocks.map(b=>renderBlock(b,chapter,assetUrl)).join('\n')}</article>`+
      `<script src="${chapter.id}-data.js"></script><script src="semantic-diagram.js"></script><script src="reader-web.js"></script></body></html>`);
    add(chapter.id+'-data.js','window.WovenChapter='+JSON.stringify({id:chapter.id,diagrams:collectDiagrams(chapter.blocks,chapter.baseSize)}).replace(/</g,'\\u003c')+';');
  }
  for(const [name,bytes] of assets)add('semantic-assets/'+name,bytes);
  const fontCss=[];
  for(const [name,file] of Object.entries(model.fonts)) {
    add('semantic-assets/'+file,await fs.readFile(path.join(work,file)));
    fontCss.push(`@font-face{font-family:source-${name};src:url(semantic-assets/${file}) format('woff');font-weight:normal;font-style:normal;font-display:block;}`);
  }
  add('semantic.css',fontCss.join('\n')+'\n'+await fs.readFile(path.join(__dirname,'lib/reader-book/semantic-preview.css'),'utf8'));
  for(const file of ['reader-web.css','reader-web.js','semantic-diagram.js'])add(file,await fs.readFile(path.join(__dirname,'lib/reader-book',file)));
  add('book-manifest.json',JSON.stringify({schemaVersion:2,source:model.source,chapters:config.chapters,pages:config.pages.map(p=>p.number)}));
  const bytes=await zip.generateAsync({type:'nodebuffer',compression:'DEFLATE',compressionOptions:{level:9}});
  const hash=createHash('sha256').update(bytes).digest('hex').slice(0,20);
  await fs.writeFile(path.join(root,'entry/src/main/resources/rawfile/reader/yaramaika-semantic.zip'),bytes);
  await fs.writeFile(path.join(root,'entry/src/main/ets/services/WebReflowContent.ets'),'// Generated by scripts/rebuild-reader-semantic-full.cjs.\n'+
    `export const WEB_REFLOW_CACHE: string = '${hash}';\n`+
    `export const WEB_REFLOW_PROGRESS: string = 'yaramaika-reflow-web-v${config.application.revision}';\n`+
    `export const WEB_REFLOW_PATCH_BYTES: number = ${bytes.length};\n`+
    `export const WEB_REFLOW_BASE_BYTES: number = 0;\n`+
    `export const WEB_REFLOW_CHAPTERS: string[] = ${JSON.stringify(config.chapters.map(c=>c.id))};\n`+
    `export const WEB_REFLOW_TITLES: string[] = ${JSON.stringify(config.chapters.map(c=>c.title))};\n`+
    `export const WEB_REFLOW_SOURCE_PAGES: number[] = ${JSON.stringify(config.chapters.map(c=>c.startPage-1))};\n`);
  console.log(JSON.stringify({chapters:model.chapters.length,sourcePages:config.pages.length,assets:assets.size,bytes:bytes.length,cache:hash,
    preview:'docs/previews/reader-semantic-full.html',audit:'docs/previews/reader-semantic-full-audit.json'},null,2));
}
if(require.main===module)main().catch(error=>{console.error(error.stack);process.exitCode=1;});
module.exports={main};
